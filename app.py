class injury_risk_predictor(nn.Module):
    def __init__(self, input_size, num_layers=2, hidden_size=64, dropout=0.3):
        super(injury_risk_predictor, self).__init__()
        self.lstm = nn.LSTM(
             input_size=input_size,
             hidden_size=hidden_size,
             num_layers=num_layers,
             batch_first=True,
             dropout=dropout
        )

        self.fc = nn.Linear(hidden_size, 3)

    def forward(self, x):
        lstm_output, _ = self.lstm(x)
        h_final_layer = lstm_output[:, -1, :]
        output = self.fc(h_final_layer)
        return output



