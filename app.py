def risk_insight(seq_array, features):
    info_explain = []
    last_day = seq_array[-1]
    weekly_avg = seq_array.mean(axis=0)

    for i, f in enumerate(features):
        if last_day[i] > weekly_avg[i]:
            info_explain.append(f"{f} increased recently")
    return info_explain[:3]

